def enrich_file(path: Path, dry_run: bool = False, sample: int = 0, force: bool = False, style: str = "linear") -> int:
    """Read, enrich, and rewrite a training.jsonl file. Returns record count."""
    records = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            if force or "thinking" not in rec:
                rec["thinking"] = generate_thinking(
                    rec["question"], rec["api_call"], style=style
                )
            records.append(rec)

    if sample > 0:
        for rec in records[:sample]:
            print(f"\nQ: {rec['question']!r}")
            print(f"Thinking:\n{rec['thinking']}")
            print(f"Answer: {json.dumps(rec['api_call'])[:80]}")
        return len(records)

    if not dry_run:
        with open(path, "w") as f:
            for rec in records:
                f.write(json.dumps(rec) + "\n")

    return len(records)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--input-dir", required=True,
                        help="Directory containing endpoint subdirs with training.jsonl")
    parser.add_argument("--endpoint", default=None,
                        help="Process only this endpoint subdirectory")
    parser.add_argument("--trace-style", choices=["linear", "qoc"], default="linear",
                        help="Thinking trace format: 'linear' (Entity/Scope/Use) or 'qoc' (Question/Option/Criteria)")
    parser.add_argument("--force", action="store_true",
                        help="Re-generate thinking for records that already have it")
    parser.add_argument("--dry-run", action="store_true",
                        help="Do not write files — print counts only")
    parser.add_argument("--sample", type=int, default=0,
                        help="Print N sample thinking traces instead of writing")
    args = parser.parse_args()

    input_dir = Path(args.input_dir).expanduser()
    if not input_dir.is_dir():
        sys.exit(f"Not a directory: {input_dir}")

    if args.endpoint:
        files = [input_dir / args.endpoint / "training.jsonl"]
    else:
        files = sorted(input_dir.glob("*/training.jsonl"))

    if not files:
        sys.exit(f"No training.jsonl files found under {input_dir}")

    total = 0
    for path in files:
        if not path.exists():
            print(f"  SKIP  {path} (not found)")
            continue
        count = enrich_file(path, dry_run=args.dry_run, sample=args.sample, force=args.force, style=args.trace_style)
        action = "would write" if args.dry_run else "wrote"
        print(f"  {action}  {count:4d} records  {path.parent.name}")
        total += count

    print(f"\n  Total: {total} records across {len(files)} endpoint(s)")
    if args.dry_run:
        print("  (dry run — no files modified)")


if __name__ == "__main__":
    main()
