_EP_ENTITY = [
    (r"/content/programs/\{",        "program",      True),
    (r"/content/programs$",          "programs",     False),
    (r"/content/episodes/\{",        "episode",      True),
    (r"/content/episodes$",          "episodes",     False),
    (r"/content/networks/\{",        "network",      True),
    (r"/content/networks$",          "networks",     False),
    (r"/content/media-groups$",      "media groups", False),
    (r"/content/metric-type",        "metric types", False),
    (r"/content/metrics/\{",         "content metric", True),
    (r"/measurements/\{",            "measurement",  True),
    (r"/measurements$",              "measurements", False),
    (r"/audiences/status$",          "audience statuses", False),
    (r"/audiences/\{[^}]+\}/exports",  "audience exports", False),
    (r"/audiences/\{",               "audience",     True),
    (r"/audiences$",                 "audiences",    False),
    (r"/currency-of-record",         "currency of record", False),
    (r"/consents$",                  "consents",     False),
    (r"/v1/me$",                     "me",           False),
]

def _infer(endpoint: str):
    """Return (entity_name, is_by_id) for an endpoint string."""
    for pattern, name, by_id in _EP_ENTITY:
        if re.search(pattern, endpoint):
            return name, by_id
    # Fallback: extract last path segment
    parts = endpoint.rstrip("/").split("/")
    last = parts[-1] if parts else "resource"
    is_by_id = last.startswith("{")
    if is_by_id:
        entity = parts[-2] if len(parts) > 1 else "resource"
    else:
        entity = last.replace("-", " ")
    return entity, is_by_id


